#!/usr/bin/env node
/*
 * Generates the SEO files from js/config.js and js/menu-data.js:
 *   - the schema.org Restaurant JSON-LD inside index.html (between the SCHEMA markers)
 *   - sitemap.xml and robots.txt
 *   - the site address in index.html's canonical, hreflang and share-preview tags
 * Run after changing the restaurant details or the menu:  node tools/build-seo.js
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const ctx = { window: {} };
vm.createContext(ctx);
for (const f of ["js/config.js", "js/menu-data.js", "js/i18n.js"]) {
  vm.runInContext(fs.readFileSync(path.join(root, f), "utf8"), ctx, { filename: f });
}
const C = ctx.window.CONFIG;
const MENU = ctx.window.MENU;
const I18N = ctx.window.I18N;
const site = C.siteUrl.replace(/\/$/, "");

const priceOf = (it) => (it.prices ? Math.min(...Object.values(it.prices)) : it.price);
const offer = (price, name) => ({ "@type": "Offer", price: String(price), priceCurrency: "MAD", ...(name ? { name } : {}) });

// One Restaurant per location; they share one menu.
const menu = {
  "@type": "Menu",
  "@id": site + "/#menu",
  name: "Menu Chicken Amine",
  inLanguage: "fr",
  hasMenuSection: MENU.map((c) => ({
    "@type": "MenuSection",
    name: c.fr,
    hasMenuItem: c.items.map((it) => {
      const item = { "@type": "MenuItem", name: it.fr };
      if (it.desc) item.description = it.desc.fr;
      item.offers = it.prices
        ? Object.entries(it.prices).map(([size, p]) => offer(p, size))
        : offer(priceOf(it));
      return item;
    }),
  })),
};
const restaurant = (loc, i) => ({
  "@type": "Restaurant",
  "@id": site + "/#" + loc.id,
  name: C.name + " " + loc.short.fr,
  url: site + "/",
  logo: site + "/assets/logo-1200.png",
  image: site + "/" + C.shareImage,
  telephone: loc.phoneIntl,
  servesCuisine: ["Fast-food", "Tacos", "Burgers", "Pizza", "Sandwichs"],
  priceRange: "$",
  currenciesAccepted: "MAD",
  address: {
    "@type": "PostalAddress",
    streetAddress: loc.streetAddress,
    addressLocality: "Casablanca",
    ...(loc.postalCode ? { postalCode: loc.postalCode } : {}),
    addressCountry: "MA",
  },
  geo: { "@type": "GeoCoordinates", latitude: loc.location.lat, longitude: loc.location.lng },
  hasMap: loc.googleMapsUrl,
  sameAs: [loc.instagram, loc.googleMapsUrl],
  openingHoursSpecification: [{
    "@type": "OpeningHoursSpecification",
    dayOfWeek: ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
    opens: C.hours.open,
    closes: C.hours.close === "00:00" ? "23:59" : C.hours.close,
  }],
  acceptsReservations: false,
  hasMenu: i === 0 ? menu : { "@id": menu["@id"] },
});
const schema = { "@context": "https://schema.org", "@graph": C.locations.map(restaurant) };

const json = JSON.stringify(schema, null, 2).replace(/</g, "\\u003c");
const block = `<!-- SCHEMA:START (generated by tools/build-seo.js from js/config.js and js/menu-data.js; do not edit by hand) -->
  <script type="application/ld+json">
${json.split("\n").map((l) => "  " + l).join("\n")}
  </script>
  <!-- SCHEMA:END -->`;

const indexPath = path.join(root, "index.html");
let html = fs.readFileSync(indexPath, "utf8");
html = html.replace(/<!-- SCHEMA:START[\s\S]*?<!-- SCHEMA:END -->/, block);
// Site address, French title and description in the head tags.
html = html
  .replace(/(<link rel="canonical" href=")[^"]*(")/, `$1${site}/$2`)
  .replace(/(<link rel="alternate" hreflang="fr" href=")[^"]*(")/, `$1${site}/$2`)
  .replace(/(<link rel="alternate" hreflang="ar" href=")[^"]*(")/, `$1${site}/?lang=ar$2`)
  .replace(/(<link rel="alternate" hreflang="x-default" href=")[^"]*(")/, `$1${site}/$2`)
  .replace(/(<meta property="og:url" content=")[^"]*(")/, `$1${site}/$2`)
  .replace(/(<meta property="og:image" content=")[^"]*(")/, `$1${site}/${C.shareImage}$2`)
  .replace(/(<title>)[^<]*(<\/title>)/, `$1${I18N.fr.meta.title}$2`)
  .replace(/(<meta name="description" content=")[^"]*(")/, `$1${I18N.fr.meta.description}$2`);
fs.writeFileSync(indexPath, html);

const today = new Date().toISOString().slice(0, 10);
const alt = `
    <xhtml:link rel="alternate" hreflang="fr" href="${site}/"/>
    <xhtml:link rel="alternate" hreflang="ar" href="${site}/?lang=ar"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${site}/"/>`;
fs.writeFileSync(path.join(root, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
  <url>
    <loc>${site}/</loc>
    <lastmod>${today}</lastmod>${alt}
  </url>
  <url>
    <loc>${site}/?lang=ar</loc>
    <lastmod>${today}</lastmod>${alt}
  </url>
</urlset>
`);

fs.writeFileSync(path.join(root, "robots.txt"), `User-agent: *
Allow: /
Disallow: /avis/
Disallow: /print/

Sitemap: ${site}/sitemap.xml
`);

const items = MENU.reduce((n, c) => n + c.items.length, 0);
console.log(`schema: ${MENU.length} sections, ${items} items · sitemap.xml · robots.txt · site ${site}`);
