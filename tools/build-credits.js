#!/usr/bin/env node
/*
 * Generates credits/index.html, the photo credits page linked from the footer, from assets/photos/credits.json
 * (title, author, licence and source of each freely licensed photo; the other photos are the restaurant's own).
 * Run after adding or changing a credited photo:  node tools/build-credits.js
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const ctx = { window: {} };
vm.createContext(ctx);
for (const f of ["js/config.js", "js/menu-data.js"]) vm.runInContext(fs.readFileSync(path.join(root, f), "utf8"), ctx, { filename: f });
const MENU = ctx.window.MENU;
const credits = JSON.parse(fs.readFileSync(path.join(root, "assets/photos/credits.json"), "utf8"));
const esc = (s) => String(s || "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

// Each credited photo, with the dishes and categories that show it.
const uses = {};
MENU.forEach((c) => {
  const file = (c.image || "").replace(/^.*\/|\.webp$/g, "");
  if (credits[file]) (uses[file] = uses[file] || []).push(`${c.fr} (catégorie)`);
  c.items.forEach((it) => {
    const f = (it.image || "").replace(/^.*\/|\.webp$/g, "");
    if (credits[f]) (uses[f] = uses[f] || []).push(it.fr);
  });
});
const rows = Object.keys(uses).sort().map((f) => {
  const c = credits[f];
  return `      <li><img src="/assets/photos/${f}.webp" alt="" width="120" height="90">
        <div><strong>${esc(uses[f].join(", "))}</strong><br>
        « ${esc(c.title)} » · ${esc(c.creator || "auteur inconnu")} · <a href="${esc(c.licenseUrl)}" rel="noopener license">${esc(c.license)}</a> · <a href="${esc(c.source)}" rel="noopener">source</a></div></li>`;
}).join("\n");

fs.writeFileSync(path.join(root, "credits/index.html"), `<!doctype html>
<html lang="fr" dir="ltr">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex">
  <title>Chicken Amine · Crédits photos</title>
  <link rel="icon" href="/favicon.ico" sizes="48x48">
  <link href="https://fonts.googleapis.com/css2?family=Baloo+2:wght@700;800&family=Cairo:wght@600;700&family=Poppins:wght@400;600&display=swap" rel="stylesheet">
  <!-- generated by tools/build-credits.js from assets/photos/credits.json; do not edit by hand -->
  <style>
    body { margin: 0; background: #e1060f; color: #1d1d1d; font-family: "Poppins", "Cairo", sans-serif; padding: 20px 16px; box-sizing: border-box; }
    .card { background: #fff; border-radius: 22px; padding: 24px 20px; max-width: 760px; margin: 0 auto; box-shadow: 0 20px 40px -24px rgba(0,0,0,.6); }
    .card > img { width: 180px; height: auto; display: block; margin: 0 0 12px; }
    h1 { font-family: "Baloo 2", sans-serif; color: #e1060f; font-size: 1.7rem; margin: 0 0 8px; }
    p { margin: 0 0 8px; }
    [lang="ar"] { font-family: "Cairo", sans-serif; direction: rtl; }
    ul { list-style: none; margin: 18px 0 0; padding: 0; }
    li { display: flex; gap: 12px; align-items: center; padding: 10px 0; border-top: 1px solid #ececec; font-size: .88rem; overflow-wrap: anywhere; }
    li img { width: 96px; height: 72px; object-fit: cover; border-radius: 10px; flex: none; }
    a { color: #a8040b; }
    a.btn { display: inline-block; margin-top: 18px; background: #fbba00; color: #141414; font-weight: 700; text-decoration: none; padding: 12px 22px; border-radius: 999px; }
  </style>
</head>
<body>
  <main class="card">
    <img src="/assets/logo.png" alt="Chicken Amine" width="640" height="332">
    <h1>Crédits photos</h1>
    <p>Les photos ci-dessous illustrent nos plats en attendant nos propres photos. Elles sont publiées sous licence libre par leurs auteurs ; les autres photos du site sont celles du restaurant.</p>
    <p lang="ar">الصور أسفله توضح أطباقنا في انتظار صورنا الخاصة، وهي منشورة برخصة حرة من طرف أصحابها. باقي صور الموقع هي صور المطعم.</p>
    <ul>
${rows}
    </ul>
    <a class="btn" href="/">Voir le menu</a>
  </main>
</body>
</html>
`);
console.log(`credits: ${Object.keys(uses).length} photos`);
